import pandas as pd
import os

# ----------------------------------------------------------------------
# 1. Запрос путей к файлам и имени столбца у пользователя
# ----------------------------------------------------------------------
file1 = input("Введите путь к первому файлу (Excel или CSV): ").strip()
file2 = input("Введите путь ко второму файлу (Excel или CSV): ").strip()
column_name = input("Введите название столбца для сравнения (например, 'ФИО'): ").strip()

# ----------------------------------------------------------------------
# 2. Загрузка данных из файлов (поддерживаются .xlsx, .xls, .csv)
# ----------------------------------------------------------------------
def load_data(file_path):
    """Загружает данные из Excel или CSV в DataFrame."""
    ext = os.path.splitext(file_path)[1].lower()
    try:
        if ext in ['.xlsx', '.xls']:
            return pd.read_excel(file_path)
        elif ext == '.csv':
            return pd.read_csv(file_path, encoding='utf-8')
        else:
            print(f"Неподдерживаемый формат файла: {ext}")
            return None
    except Exception as e:
        print(f"Ошибка при загрузке файла {file_path}: {e}")
        return None

print("\nЗагрузка файлов...")
df1 = load_data(file1)
df2 = load_data(file2)

if df1 is None or df2 is None:
    print("Не удалось загрузить один из файлов. Проверьте пути и формат.")
    exit()

# ----------------------------------------------------------------------
# 3. Проверка наличия указанного столбца в обоих файлах
# ----------------------------------------------------------------------
if column_name not in df1.columns:
    print(f"Столбец '{column_name}' не найден в первом файле. Доступные столбцы: {list(df1.columns)}")
    exit()
if column_name not in df2.columns:
    print(f"Столбец '{column_name}' не найден во втором файле. Доступные столбцы: {list(df2.columns)}")
    exit()

# ----------------------------------------------------------------------
# 4. Сравнение значений в столбце (без учёта дубликатов – простой вариант)
# ----------------------------------------------------------------------
values1 = set(df1[column_name].dropna())  # уникальные значения из первого файла
values2 = set(df2[column_name].dropna())  # уникальные значения из второго файла

only_in_1 = values1 - values2   # есть только в первом файле
only_in_2 = values2 - values1   # есть только во втором файле

print(f"\nУникальных значений в первом файле: {len(values1)}")
print(f"Уникальных значений во втором файле: {len(values2)}")
print(f"Значений, которых нет во втором файле: {len(only_in_1)}")
print(f"Значений, которых нет в первом файле: {len(only_in_2)}")

# ----------------------------------------------------------------------
# 5. Отбор строк, которые не совпадают
# ----------------------------------------------------------------------
# Строки из первого файла, чьи значения в столбце отсутствуют во втором
mismatch_df1 = df1[df1[column_name].isin(only_in_1)].copy()
mismatch_df1['Источник'] = 'Только в первом файле'

# Строки из второго файла, чьи значения в столбце отсутствуют в первом
mismatch_df2 = df2[df2[column_name].isin(only_in_2)].copy()
mismatch_df2['Источник'] = 'Только во втором файле'

# Объединяем результаты
result = pd.concat([mismatch_df1, mismatch_df2], ignore_index=True)

if result.empty:
    print("\nВсе значения совпадают! Несовпадающих строк нет.")
    exit()

# ----------------------------------------------------------------------
# 6. Сохранение результата в новый Excel-файл
# ----------------------------------------------------------------------
output_file = "результат_сравнения.xlsx"
try:
    result.to_excel(output_file, sheet_name="Несовпадения", index=False)
    print(f"\nРезультат сохранён в файл: {output_file}")
    print(f"Всего несовпадающих строк: {len(result)}")
except Exception as e:
    print(f"Ошибка при сохранении результата: {e}")

# ----------------------------------------------------------------------
# 7. Дополнительная информация (опционально)
# ----------------------------------------------------------------------
print("\nПример несовпадающих значений:")
if len(only_in_1) > 0:
    print(f"  Из первого файла, отсутствующие во втором (первые 5): {list(only_in_1)[:5]}")
if len(only_in_2) > 0:
    print(f"  Из второго файла, отсутствующие в первом (первые 5): {list(only_in_2)[:5]}")
